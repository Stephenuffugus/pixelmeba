/**
 * P4.10 (UX §10 "Icon: the dish with one bright colony, no text"; ARCH §12 "Splash and adaptive icon"):
 * compile art/src/icons/appIcon.ts into the Android launcher icons, the adaptive-icon background colour, the
 * splash images Capacitor's template uses, and the web manifest icons.
 *
 *   npx tsx tools/android-icons.ts            write every file
 *   npx tsx tools/android-icons.ts --check    exit 1 when a file on disk differs from what would be written
 *
 * Nearest-neighbour at INTEGER scales only (every matrix cell is a solid k × k block). Deterministic: the same
 * matrices always give the same bytes (tests/tools/android-icons.test.ts writes twice and compares).
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';
import { hexToRgba } from '../art/src/palette';
import type { Px } from '../art/src/px';
import { FOREGROUND_GRID, ICON_BACKGROUND, ICON_PALETTE, iconComposite, iconForeground, iconLegacy, LEGACY_GRID, SAFE_RADIUS } from '../art/src/icons/appIcon';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RES = 'android/app/src/main/res';

/** Android densities and their integer scale of the 54-cell foreground and the 24-cell legacy grid. */
export const DENSITIES = [
  { name: 'mdpi', k: 2 },
  { name: 'hdpi', k: 3 },
  { name: 'xhdpi', k: 4 },
  { name: 'xxhdpi', k: 6 },
  { name: 'xxxhdpi', k: 8 },
] as const;

/** The splash images in Capacitor 8's Android template (sizes as generated by `cap add android`). */
export const SPLASHES: readonly { readonly dir: string; readonly w: number; readonly h: number }[] = [
  { dir: 'drawable', w: 480, h: 320 },
  { dir: 'drawable-land-mdpi', w: 480, h: 320 },
  { dir: 'drawable-land-hdpi', w: 800, h: 480 },
  { dir: 'drawable-land-xhdpi', w: 1280, h: 720 },
  { dir: 'drawable-land-xxhdpi', w: 1600, h: 960 },
  { dir: 'drawable-land-xxxhdpi', w: 1920, h: 1280 },
  { dir: 'drawable-port-mdpi', w: 320, h: 480 },
  { dir: 'drawable-port-hdpi', w: 480, h: 800 },
  { dir: 'drawable-port-xhdpi', w: 720, h: 1280 },
  { dir: 'drawable-port-xxhdpi', w: 960, h: 1600 },
  { dir: 'drawable-port-xxxhdpi', w: 1280, h: 1920 },
];

/** One output: its repository path, size, and whether it may have transparency. */
export interface IconFile {
  readonly path: string;
  readonly bytes: Buffer;
  readonly w: number;
  readonly h: number;
  /** The art's integer scale and where its top-left lands (the tests check the k × k blocks). */
  readonly scale: number;
  readonly origin: readonly [number, number];
  readonly grid: number;
}

const RGBA = ICON_PALETTE.map((hex) => (hex === '' ? ([0, 0, 0, 0] as const) : hexToRgba(hex)));

/** Draw `art` at integer scale k with its top-left at (ox, oy) onto a w × h canvas filled with `fill`. */
function render(art: Px, k: number, w: number, h: number, ox: number, oy: number, fill: readonly number[] | null): Uint8Array {
  if (!Number.isInteger(k) || k < 1) throw new Error(`scale ${k} is not a positive integer`);
  const out = new Uint8Array(w * h * 4);
  if (fill) for (let i = 0; i < w * h; i++) out.set(fill, i * 4);
  for (let y = 0; y < art.h; y++) {
    for (let x = 0; x < art.w; x++) {
      const v = art.get(x, y);
      if (v === 0) continue;
      const c = RGBA[v]!;
      for (let dy = 0; dy < k; dy++) for (let dx = 0; dx < k; dx++) out.set(c, ((oy + y * k + dy) * w + (ox + x * k + dx)) * 4);
    }
  }
  return out;
}

/** PNG bytes: RGBA when `alpha`, else RGB (an opaque image carries no alpha channel). */
function png(rgba: Uint8Array, w: number, h: number, alpha: boolean): Buffer {
  const p = new PNG({ width: w, height: h, colorType: alpha ? 6 : 2, inputColorType: 6, inputHasAlpha: true, deflateLevel: 9 });
  p.data = Buffer.from(rgba);
  return PNG.sync.write(p, { colorType: alpha ? 6 : 2, inputColorType: 6, inputHasAlpha: true, deflateLevel: 9 });
}

const BG = hexToRgba(ICON_BACKGROUND);

function file(path: string, art: Px, k: number, w: number, h: number, fill: readonly number[] | null): IconFile {
  const ox = Math.floor((w - art.w * k) / 2);
  const oy = Math.floor((h - art.h * k) / 2);
  return { path, bytes: png(render(art, k, w, h, ox, oy, fill), w, h, fill === null), w, h, scale: k, origin: [ox, oy], grid: art.w };
}

/** Every PNG this tool writes (not written yet). */
export function renderIcons(): IconFile[] {
  const fg = iconForeground();
  const square = iconLegacy('square');
  const round = iconLegacy('round');
  const composite = iconComposite();
  const out: IconFile[] = [];
  for (const d of DENSITIES) {
    const fgPx = FOREGROUND_GRID * d.k; // 108 / 162 / 216 / 324 / 432
    const legacyPx = LEGACY_GRID * d.k; // 48 / 72 / 96 / 144 / 192
    out.push(file(`${RES}/mipmap-${d.name}/ic_launcher_foreground.png`, fg, d.k, fgPx, fgPx, null));
    out.push(file(`${RES}/mipmap-${d.name}/ic_launcher.png`, square, d.k, legacyPx, legacyPx, BG));
    out.push(file(`${RES}/mipmap-${d.name}/ic_launcher_round.png`, round, d.k, legacyPx, legacyPx, null));
  }
  for (const s of SPLASHES) {
    // The icon centred on the outside colour, at the largest integer scale where the dish (the safe circle,
    // 33 cells across) takes at most half the short side; the 54-cell canvas then always fits.
    const k = Math.max(1, Math.floor(Math.min(s.w, s.h) / (2 * Math.ceil(2 * SAFE_RADIUS))));
    out.push(file(`${RES}/${s.dir}/splash.png`, composite, k, s.w, s.h, BG));
  }
  // The web manifest icons (P4.11 links them): opaque, the art centred at an integer scale.
  out.push(file('public/icons/icon-192.png', square, 8, 192, 192, BG));
  out.push(file('public/icons/icon-512.png', square, 21, 512, 512, BG));
  out.push(file('public/icons/maskable-512.png', composite, 9, 512, 512, BG));
  return out;
}

/** The adaptive icon's background colour resource. */
export function backgroundXml(): string {
  return `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <!-- P4.10: the adaptive icon's background layer (art/src/icons/appIcon.ts ICON_BACKGROUND, palette "outside"). -->\n    <color name="ic_launcher_background">${ICON_BACKGROUND}</color>\n</resources>\n`;
}

export function allOutputs(): { path: string; bytes: Buffer }[] {
  return [...renderIcons().map((f) => ({ path: f.path, bytes: f.bytes })), { path: `${RES}/values/ic_launcher_background.xml`, bytes: Buffer.from(backgroundXml(), 'utf8') }];
}

function main(): void {
  const check = process.argv.includes('--check');
  let differ = 0;
  for (const o of allOutputs()) {
    const abs = join(ROOT, o.path);
    const same = existsSync(abs) && Buffer.compare(readFileSync(abs), o.bytes) === 0;
    if (check) {
      if (!same) {
        differ++;
        console.log(`differs: ${o.path}`);
      }
      continue;
    }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, o.bytes);
    console.log(`${same ? 'unchanged' : 'wrote'} ${o.path} (${o.bytes.length} bytes)`);
  }
  if (check) {
    console.log(differ === 0 ? 'android-icons: every file matches' : `android-icons: ${differ} file(s) differ`);
    process.exit(differ === 0 ? 0 : 1);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
